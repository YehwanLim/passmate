// 경험 자동 채우기 프롬프트의 단일 정의처. 서버 lib/experience-extract.js 만 쓴다.
// 지시는 규칙 나열보다 JSON 필드 설명에 둔다(모델이 스키마 설명을 더 잘 따른다). 예시 문장은 넣지 않는다 — 베낀다.

export const EXTRACT_MAX_CANDIDATES = 8;

export function buildExtractPrompt({ text }) {
  return [
    "너는 신입 공채 지원자가 예전에 쓴 자기소개서에서 경험을 찾아 경험 카드로 옮겨 적는 정리 담당이다.",
    "아래 [원문]에 적힌 사실만 옮긴다. 원문에 없는 숫자·성과·역할·직책·기간·도구·인물·동기·감정은 만들지 않는다.",
    "",
    "[원문]",
    text,
    "",
    "JSON 하나만 반환한다:",
    "{",
    `  "candidates": [{`,
    `    "title": "이 경험을 한 줄로 부르는 이름. 30자 안팎. 원문 표현을 살리고, 경험을 평가하거나 꾸미는 말을 붙이지 않는다",`,
    `    "period": "원문에 적힌 기간·시기를 그대로. 원문에 없으면 빈 문자열",`,
    `    "situation": "어떤 상황·문제였는지. 원문에서 이 칸에 맞는 핵심 문장 1~3개만 골라 원문 말투 그대로 옮긴다. 원문에 없으면 빈 문자열",`,
    `    "action": "지원자가 판단하고 직접 한 일. 원문에서 이 칸에 맞는 핵심 문장 1~3개만 골라 원문 말투 그대로 옮긴다. 세부 과정을 전부 옮기지 않는다. 원문에 없으면 빈 문자열",`,
    `    "result": "그래서 달라진 것. 원문에 적힌 결과 중 핵심 문장 1~3개만 골라 원문 말투 그대로 옮긴다. 원문에 없으면 빈 문자열로 두고 짐작해 채우지 않는다",`,
    `    "tags": ["원문에 나온 역량·분야 단어. 최대 5개"],`,
    `    "quotes": ["이 경험의 근거가 된 원문 문장 1~2개. 원문에서 한 글자도 바꾸지 않고 그대로 복사한다"]`,
    "  }]",
    "}",
    `candidates 는 원문에 나오는 서로 다른 경험이다. 최대 ${EXTRACT_MAX_CANDIDATES}개. 같은 경험이 여러 문항에 나오면 하나로 합친다. 지원 동기 문항 안에 있어도 지원자가 직접 겪거나 해 본 일은 경험으로 넣는다. 같은 계기로 이어진 관찰·시도·확인은 하나의 경험으로 묶는다. 다짐·포부·회사에 대한 생각처럼 겪은 일이 아닌 문장만 뺀다. 경험이 하나도 없으면 빈 배열을 돌려준다.`,
  ].join("\n");
}
