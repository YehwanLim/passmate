// 경험 카드 추천 키워드 프롬프트의 단일 정의처. 서버 lib/experience-keywords.js 만 쓴다.
// 지시는 규칙 나열보다 JSON 필드 설명에 둔다(모델이 스키마 설명을 더 잘 따른다). 예시 단어는 넣지 않는다 — 베낀다.

export const KEYWORD_MAX_SUGGESTIONS = 2;

export function buildKeywordPrompt({ title, text, known, current }) {
  return [
    "너는 신입 공채 지원자의 경험 카드에 붙일 키워드를 고르는 정리 담당이다. 키워드는 나중에 자기소개서 문항에 맞는 경험을 찾을 때 쓴다.",
    "아래 [경험]에 적힌 내용만 보고 고른다. 적히지 않은 역할·성과·도구는 짐작해 넣지 않는다.",
    "",
    "[경험 이름]",
    title || "(없음)",
    "",
    "[경험]",
    text || "(없음)",
    "",
    "[이미 쓰는 키워드]",
    known.length > 0 ? known.join(", ") : "(없음)",
    "",
    "[이미 붙인 키워드]",
    current.length > 0 ? current.join(", ") : "(없음)",
    "",
    "JSON 하나만 반환한다:",
    "{",
    `  "keywords": ["이 경험이 보여 주는 역량이나 분야를 부르는 짧은 명사. 공백 포함 2~10자. 고른 키워드와 같은 뜻이 [이미 쓰는 키워드]에 있으면 그 표기를 그대로 쓰고, 없으면 새로 짓는다. [이미 붙인 키워드]와 같은 뜻은 넣지 않는다. 이 경험에서 드러나는 서로 다른 면을 골라 ${KEYWORD_MAX_SUGGESTIONS}개까지(드러나는 면이 하나뿐이면 1개), 맞는 것이 없으면 빈 배열"]`,
    "}",
  ].join("\n");
}
