/**
 * 서버 공고 요약(POST /api/analyze/posting)에 보낼 본문. 분석 폼 '접수 중인 공고' 탭이 고른 공고를 이 글로 읽힌다.
 * 공고 원문 대신 우리가 확인해 옮긴 사실(주요 특징·핵심 정보·확인할 것)을 보낸다.
 */
export function postingTextOf(listing: JobPostingListing, detail: JobPostingDetail): string {
  return [
    listing.title,
    listing.subtitle,
    detail.highlight,
    ...detail.facts.map(fact => `${fact.label}: ${typeof fact.value === "string" ? fact.value : fact.value.join(" / ")}`),
    ...detail.process.map(track => `전형 절차${track.name ? `(${track.name})` : ""}: ${track.steps.join(" → ")}`),
    ...(detail.processNote ? [detail.processNote] : []),
    ...detail.checks,
  ].join("\n");
}
