/** 대소문자·띄어쓰기·구분기호를 무시하고 비교하기 위한 정규화. */
function normalizeJobRole(value: string) {
  return value.toLowerCase().replace(/[\s/·()]/g, "");
}

/**
 * 검색어에 걸리는 직무만 카테고리별로 묶어서 돌려준다. 빈 검색어면 전체 목록.
 *
 * 검색어로 "시작하는" 직무를 앞에 둔다. 그래야 "개발"을 쳤을 때 포괄 직무 "개발"이
 * "사업개발" 같은 부분 일치에 묻히지 않는다.
 */
export function filterJobRoleCategories(query: string) {
  const normalizedQuery = normalizeJobRole(query.trim());

  const matched = JOB_ROLE_CATEGORIES.map(category => {
    const isCategoryMatch =
      !normalizedQuery ||
      normalizeJobRole(category.name).includes(normalizedQuery);
    const roles: string[] = isCategoryMatch
      ? [...category.roles]
      : category.roles.filter(role =>
          normalizeJobRole(role).includes(normalizedQuery)
        );
    return { name: category.name, roles };
  }).filter(category => category.roles.length > 0);

  if (!normalizedQuery) return matched;

  const rankOf = (role: string) =>
    normalizeJobRole(role).startsWith(normalizedQuery) ? 0 : 1;

  return matched
    .map(category => ({
      name: category.name,
      roles: [...category.roles].sort((a, b) => rankOf(a) - rankOf(b)),
    }))
    .sort(
      (a, b) =>
        Math.min(...a.roles.map(rankOf)) - Math.min(...b.roles.map(rankOf))
    );
}
